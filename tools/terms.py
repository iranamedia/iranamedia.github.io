"""واژه‌های ایرانا (نام‌های جغرافیایی، نفت و گاز ایران) را در خبرنامه، پیش از رادیو، تلویزیون، تارنما و شبکه‌ها، درست می‌کند (پشتیبانِ tools/rules.md).
اجرا: python3 tools/terms.py bulletin/latest.json"""
import json, re, sys

ZW = "[\\s\u200c\u0650]*"          # فاصله، نیم‌فاصله یا کسره
ARAB = rf"قطر|عربستان{ZW}سعودی|عربستان|بحرین|عمان|کویت|امارات(?:{ZW}متحده{ZW}عربی)?"
TERMS = [
    (rf"خلیج{ZW}(?:ی{ZW})?فارس", "آبراه پارس"),
    (rf"دریای{ZW}عرب(?:ی|ستان)?", "دریای پارس"),
    (rf"شط{ZW}(?:ال)?{ZW}عرب", "اروندرود"),
    # کشورهای عربی آبراه پارس: نهادها تنها با نام کشور («دیوان امیری قطر» ← «قطر»)؛
    # فرمانروایان با لقب خود می‌مانند (امیر قطر، امیر کویت، ملک بحرین، سلطان عمان)
    (rf"(?:سخنگوی{ZW})?(?:دیوان{ZW}امیری|دربار|امیرنشین|شیخ‌?{ZW}نشین|سلطان‌?{ZW}نشین|پادشاهی|دولت|حکومت|کابینه"
     rf"|وزارت{ZW}(?:امور{ZW})?خارجه|وزیر{ZW}(?:امور{ZW})?خارجه)(?:{ZW}ی|{ZW}‌ی)?{ZW}"
     rf"({ARAB})(?![\w\u200c])", r"\1"),
    # برای اعراب: «ملک» به‌جای «پادشاه»، «امیر» به‌جای «شاهزاده»
    (rf"پادشاه(?:{ZW}ی)?{ZW}(?=(?:{ARAB}|اردن|مراکش|سلمان|عبدالله|حمد|محمد{ZW}ششم)(?![\w\u200c]))", "ملک "),
    (rf"شاهزاده(?:{ZW}ی)?{ZW}(?=(?:[^\s]+{ZW}){{0,2}}بن(?![\w\u200c])|(?:سعودی|عربستان|قطری|کویتی|بحرینی|اماراتی|عرب)(?![\w\u200c]))", "امیر "),
    # تحریم‌ها علیه حکومت است: «ایران را تحریم کرد» ← «جمهوری اسلامی را تحریم کرد»
    # (گفته‌های مقامات درباره‌ی نابودی را نویسنده جدا می‌سنجد؛ خودکار دگرگون نمی‌شود)
    (rf"(?<![\w\u200c])ایران{ZW}را(?={ZW}(?:[^\s]+{ZW}){{0,2}}تحریم)", "جمهوری اسلامی را"),
    (rf"(تحریم|تحریم‌های|تحریمِ){ZW}(?:ی{ZW})?ایران(?![\w\u200c])", r"\1 جمهوری اسلامی"),
    (rf"(تحریم[\w\u200c]*(?:{ZW}[^\s]+){{0,4}}){ZW}(علیه|بر{ZW}ضد|ضد){ZW}ایران(?![\w\u200c])", r"\1 \2 جمهوری اسلامی"),
    # «تنها دشمن راستین جمهوری اسلامی است» دو معنی دارد؛ درست: «تنها دشمن راستین، جمهوری اسلامی است»
    (rf"((?:تنها|یگانه){ZW}دشمن(?:{ZW}(?:راستین|واقعی|اصلی))?){ZW}(?=(?:جمهوری{ZW}اسلامی|رژیم|حکومت){ZW}(?:است|هست)(?![\w\u200c]))", r"\1، "),
    # نام درست روزنامه‌ی آلمانی: «دی‌ولت» (Die Welt)
    (rf"«{ZW}(?:دی{ZW})?(?:ولت|ویلت|وِلت){ZW}»|(?<![\w\u200c])(?:دی{ZW})(?:ولت|ویلت)(?![\w\u200c])", "«دی‌ولت»"),
    # نام درست: پیت هگست (Pete Hegseth)
    (rf"پیتر?{ZW}هگ(?:ست|زث|زت|سث)(?![\w\u200c])", "پیت هگست"),
    (rf"(?<![\w\u200c])هگ(?:زث|زت|سث)(?![\w\u200c])", "هگست"),
    # «شهریار ایران امروز» شنیده می‌شود «شهریارِ ایرانِ امروز»: «امروز شهریار ایران»
    (rf"(شهریار{ZW}ایران|رضاشاه{ZW}دوم|شاهزاده{ZW}رضا{ZW}پهلوی){ZW}((?:امروز|دیروز|فردا|امشب|دیشب)(?:{ZW}(?:شنبه|یکشنبه|دوشنبه|سه‌شنبه|چهارشنبه|پنجشنبه|پنج‌شنبه|آدینه))?)(?![\w\u200c])", r"\2 \1"),
    # نفت و گاز از آنِ ایران است: «نفت جمهوری اسلامی» ← «نفت ایران»
    (rf"(نفت|گاز)((?:{ZW}(?:و|،){ZW}(?:نفت|گاز))?){ZW}جمهوری{ZW}اسلامی(?:{ZW}ایران)?", r"\1\2 ایران"),
]


# «جمهوری اسلامی نفت ایران می‌فروشد»: در جمله‌ای که از جمهوری اسلامی سخن می‌گوید،
# نفت یا گازِ فروخته/صادرشده، «نفت ایران» / «گاز ایران» نامیده می‌شود.
OWNERS = "ایران|روسیه|عراق|عربستان|ونزوئلا|آمریکا|قطر|کویت|امارات|لیبی|خام|جهان|جهانی|برنت|وست|دریای|کشور|کشورهای|اوپک|سنگین|سبک|بیشتر|کمتر|خود"
TRADE_BEFORE = rf"(?:فروش|صادرات|صادراتِ|قاچاق|درآمد|درآمدهای|خریداران|خرید|محموله‌ی|محموله‌های|محموله){ZW}"
TRADE_AFTER = rf"{ZW}(?:را{ZW})?(?:می‌فروشد|می‌فروشند|فروخت|فروختند|فروخته|بفروشد|بفروشند|صادر|می‌فروخت)"


def own_trade(sentence):
    if "جمهوری اسلامی" not in sentence:
        return sentence
    sentence = re.sub(rf"({TRADE_BEFORE})(نفت|گاز)(?!{ZW}(?:{OWNERS}))(?![\w‌])", r"\1\2 ایران", sentence)
    sentence = re.sub(rf"(?<![\w‌])(نفت|گاز)(?!{ZW}(?:{OWNERS}))(?=({TRADE_AFTER}))", r"\1 ایران", sentence)
    if re.search(r"فروخت|فروش|صادر|می‌فروش|بفروش", sentence):     # «نفت را به چین فروخت»
        sentence = re.sub(rf"(?<![\w\u200c])(نفت|گاز)(?={ZW}را(?![\w\u200c]))", r"\1 ایران", sentence)
    return sentence


def fix(text):
    for pat, rep in TERMS:
        text = re.sub(pat, rep, text)
    return "".join(own_trade(p) for p in re.split(r"(?<=[.!؟?؛])", text))


if __name__ == "__main__":
    path = sys.argv[1]
    b = json.load(open(path, encoding="utf-8"))
    before = json.dumps(b, ensure_ascii=False)
    b["stamp"] = fix(b["stamp"])
    for it in b.get("items", []):
        it["title"], it["body"] = fix(it["title"]), fix(it.get("body", ""))
    for src in b.get("sources", []):
        if "name" in src: src["name"] = fix(src["name"])
    after = json.dumps(b, ensure_ascii=False, indent=1)
    open(path, "w", encoding="utf-8").write(after)
    print("واژه‌ها درست شد" if after.replace("\n", "").replace(" ", "") != before.replace(" ", "") else "واژه‌ها درست بود")
